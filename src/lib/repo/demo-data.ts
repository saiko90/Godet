/** Parc d'exemple pour le jour `today` (AAAA-MM-JJ). Identifiants stables : /demo?m=demo-pe-01 ouvre PE-01. */
export function buildDemoSeed(today: string): DemoSeed {
  const shift = daysBetween(REF, today);
  /** Jour d'une définition : chaîne = date de la migration (recalée), nombre = décalage depuis aujourd'hui. */
  const dayOf = (d: number | string) => (typeof d === 'string' ? addDays(d, shift) : addDays(today, d));
  const created = zurichISO(addDays(today, -400), 9);

  const org: Org = {
    id: DEMO_ORG_ID,
    name: 'Entreprise Démo SA',
    canton: 'VS',
    country: 'CH',
    currency: 'CHF',
    plan: 'essai',
    trial_ends_at: zurichISO(addDays(today, 30), 0),
    created_by: DEMO_USER_ID,
    created_at: created,
  };

  const machines: Machine[] = [];
  const schedules: Schedule[] = [];
  const entries: Entry[] = [];
  const readings: HourReading[] = [];
  let readingId = 1;
  const read = (machineId: string, hours: number, at: string, source: string) => {
    readings.push({ id: readingId++, org_id: org.id, machine_id: machineId, hours, read_at: at, source, created_by: DEMO_USER_ID });
  };

  FLEET.forEach((def, position) => {
    const id = `demo-${def.slug}`;
    const isSql = def.perDay === 0;
    const hoursAt = (offset: number) => Math.round(def.hours + def.perDay * (offset - def.lastRead));
    const lastReadAt = zurichISO(addDays(today, def.lastRead), 7, 15);
    const machineCreated = isSql ? zurichISO(today, 7, 30) : created;

    machines.push({
      id,
      org_id: org.id,
      code: def.code,
      kind: def.kind,
      brand: def.brand,
      model: def.model,
      year: def.year,
      serial: def.serial,
      plate: def.plate,
      weight_t: def.weight,
      color: def.color,
      hours: def.hours,
      hours_at: isSql ? machineCreated : lastReadAt,
      position,
      notes: def.notes,
      archived_at: null,
      created_by: DEMO_USER_ID,
      created_at: machineCreated,
      updated_at: machineCreated,
    });

    // Relevés : création, relevés réguliers, dernier relevé (comme les déclencheurs de la base).
    if (isSql) {
      read(id, def.hours, machineCreated, 'creation');
      read(id, 6806, zurichISO(addDays(today, -7), 7, 30), 'saisie');
    } else {
      read(id, hoursAt(-400), created, 'creation');
      if (def.routineReadings) {
        for (let o = -112; o < def.lastRead; o += 14) read(id, hoursAt(o), zurichISO(addDays(today, o), 7, 15), 'saisie');
      }
      read(id, def.hours, lastReadAt, 'saisie');
    }

    def.entries.forEach((e, i) => {
      const [kind, day, h, title, details, by, parts, labour, downtime, status, ref, qty, warranty, supplier, removed] = e;
      const date = dayOf(day);
      const offset = daysBetween(today, date);
      const hours = h === 'auto' ? hoursAt(offset) : h;
      const at = zurichISO(date, 17, 30);
      const entryId = `${id}-e${String(i + 1).padStart(2, '0')}`;
      entries.push({
        id: entryId,
        org_id: org.id,
        machine_id: id,
        kind,
        date,
        hours,
        title,
        details,
        performed_by: by,
        cost_parts: parts,
        cost_labour: labour,
        downtime_hours: downtime,
        repair_status: kind === 'reparation' ? status : null,
        part_ref: ref,
        part_qty: qty,
        supplier: supplier ?? null,
        warranty_until: warranty == null ? null : typeof warranty === 'string' ? dayOf(warranty) : addDays(date, warranty),
        schedule_id: null,
        created_by: DEMO_USER_ID,
        created_at: at,
        updated_at: removed ? zurichISO(addDays(date, removed.after), 8) : at,
        deleted_at: removed ? zurichISO(addDays(date, removed.after), 8) : null,
        deleted_by: removed ? DEMO_USER_ID : null,
        delete_reason: removed ? removed.reason : null,
      });
      // Déclencheur : une saisie avec compteur crée un relevé à midi (heure suisse).
      if (hours != null) read(id, hours, zurichISO(date, 12), 'intervention');
    });

    def.schedules.forEach((s, i) => {
      const base = {
        id: `${id}-s${i + 1}`,
        org_id: org.id,
        machine_id: id,
        label: s.label,
        active: true,
        created_at: created,
      };
      if (s.basis === 'heures') {
        schedules.push({
          ...base,
          basis: 'heures',
          interval_hours: s.every,
          interval_days: null,
          last_hours: s.last,
          last_date: s.lastDay == null ? null : dayOf(s.lastDay),
          due_hours: s.due,
          due_date: null,
        });
      } else {
        schedules.push({
          ...base,
          basis: 'date',
          interval_hours: null,
          interval_days: s.everyDays,
          last_hours: null,
          last_date: s.lastDay == null ? null : dayOf(s.lastDay),
          due_hours: null,
          due_date: dayOf(s.dueDay),
        });
      }
    });
  });

  readings.sort((a, b) => a.read_at.localeCompare(b.read_at));
  return { org, userId: DEMO_USER_ID, today, machines, schedules, entries, readings, media: [] };
}
