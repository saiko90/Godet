/** Saisie : [type, jour (décalage depuis aujourd'hui ou date de la migration), compteur, titre, détails, fait par,
 *  pièces CHF, main-d'œuvre CHF, immobilisation h, statut, réf., qté, garantie (décalage en jours depuis la saisie), fournisseur] */
type EntryDef = [
  kind: EntryKind,
  day: number | string,
  hours: number | 'auto' | null,
  title: string,
  details: string | null,
  by: string | null,
  parts: number,
  labour: number,
  downtime: number | null,
  status: RepairStatus | null,
  ref: string | null,
  qty: number | null,
  warranty: number | string | null,
  supplier?: string | null,
  removed?: { reason: string; after: number },
];

type ScheduleDef =
  | { label: string; basis: 'heures'; every: number | null; last: number | null; lastDay: number | string | null; due: number }
  | { label: string; basis: 'date'; everyDays: number | null; lastDay: number | string | null; dueDay: number | string };

